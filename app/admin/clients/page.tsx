"use client";

import { useEffect, useState } from "react";
import { supabase } from "@/lib/supabase";
import { jsPDF } from "jspdf";

interface Client {
  id: number;
  company_name: string;
  contact_name: string;
  email: string;
  compliance_status: string;
  risk_score: number;
  industry?: string;
  framework?: string;
  findings?: string;
  recommendations?: string;
  document_url?: string;
}

export default function ClientsPage() {
  const [clients, setClients] = useState<Client[]>([]);
  const [loading, setLoading] = useState(true);

  const [companyName, setCompanyName] = useState("");
  const [contactName, setContactName] = useState("");
  const [email, setEmail] = useState("");
  const [complianceStatus, setComplianceStatus] = useState("");
  const [riskScore, setRiskScore] = useState("");

  const [industry, setIndustry] = useState("");
  const [framework, setFramework] = useState("");
  const [findings, setFindings] = useState("");
  const [recommendations, setRecommendations] = useState("");

  const [selectedFile, setSelectedFile] = useState<File | null>(null);

  const fetchClients = async () => {
    const { data, error } = await supabase
      .from("clients")
      .select("*")
      .order("created_at", { ascending: false });

    if (error) {
      console.error(error);
      return;
    }

    setClients(data || []);
    setLoading(false);
  };

  const uploadFile = async () => {
    if (!selectedFile) return null;

    const fileName = `${Date.now()}-${selectedFile.name}`;

    const { error } = await supabase.storage
      .from("client-documents")
      .upload(fileName, selectedFile);

    if (error) {
      console.error(error);
      return null;
    }

    const {
      data: { publicUrl },
    } = supabase.storage
      .from("client-documents")
      .getPublicUrl(fileName);

    return publicUrl;
  };

  const addClient = async () => {
    const uploadedFileUrl = await uploadFile();

    const { error } = await supabase
      .from("clients")
      .insert([
        {
          company_name: companyName,
          contact_name: contactName,
          email,
          compliance_status: complianceStatus,
          risk_score: Number(riskScore),
          industry,
          framework,
          findings,
          recommendations,
          document_url: uploadedFileUrl,
        },
      ]);

    if (error) {
      console.error(error);
      return;
    }

    setCompanyName("");
    setContactName("");
    setEmail("");
    setComplianceStatus("");
    setRiskScore("");
    setIndustry("");
    setFramework("");
    setFindings("");
    setRecommendations("");
    setSelectedFile(null);

    await fetchClients();
  };

  const generatePDF = (client: Client) => {
    const doc = new jsPDF();

    doc.setFillColor(0, 0, 0);
    doc.rect(0, 0, 210, 40, "F");

    doc.setTextColor(255, 255, 255);
    doc.setFontSize(28);

    doc.text("WALLACE CYBER SOLUTIONS", 20, 25);

    doc.setFontSize(18);

    doc.text("Cybersecurity Compliance Report", 20, 60);

    doc.setTextColor(0, 0, 0);

    doc.setFontSize(14);

    doc.text(`Company: ${client.company_name}`, 20, 85);
    doc.text(`Contact: ${client.contact_name}`, 20, 100);
    doc.text(`Email: ${client.email}`, 20, 115);

    doc.text(
      `Compliance Status: ${client.compliance_status}`,
      20,
      130
    );

    doc.text(`Risk Score: ${client.risk_score}`, 20, 145);

    doc.text(`Industry: ${client.industry || "N/A"}`, 20, 160);

    doc.text(
      `Framework: ${client.framework || "N/A"}`,
      20,
      175
    );

    doc.setFontSize(16);

    doc.text("Key Findings", 20, 200);

    doc.setFontSize(12);

    doc.text(
      client.findings || "No findings added.",
      20,
      215,
      {
        maxWidth: 170,
      }
    );

    doc.setFontSize(16);

    doc.text("Recommendations", 20, 250);

    doc.setFontSize(12);

    doc.text(
      client.recommendations || "No recommendations added.",
      20,
      265,
      {
        maxWidth: 170,
      }
    );

    doc.setFontSize(10);

    doc.text(
      "Generated by WALLACE CYBER SOLUTIONS",
      20,
      285
    );

    doc.save(`${client.company_name}-cyber-report.pdf`);
  };

  useEffect(() => {
    const loadData = async () => {
      await fetchClients();
    };

    loadData();
  }, []);

  return (
    <main className="min-h-screen bg-black text-white p-8">
      <div className="max-w-7xl mx-auto">

        <div className="mb-12">
          <h1 className="text-5xl font-bold">
            Client Management
          </h1>

          <p className="mt-4 text-zinc-400">
            Enterprise Cybersecurity Assessment Platform
          </p>
        </div>

        <div className="mb-12 rounded-3xl border border-white/10 bg-white/5 p-8">

          <h2 className="text-2xl font-semibold mb-6">
            Add Client Assessment
          </h2>

          <div className="grid md:grid-cols-2 gap-6">

            <input
              placeholder="Company Name"
              value={companyName}
              onChange={(e) => setCompanyName(e.target.value)}
              className="rounded-2xl bg-black border border-white/10 px-4 py-4"
            />

            <input
              placeholder="Contact Name"
              value={contactName}
              onChange={(e) => setContactName(e.target.value)}
              className="rounded-2xl bg-black border border-white/10 px-4 py-4"
            />

            <input
              placeholder="Email"
              value={email}
              onChange={(e) => setEmail(e.target.value)}
              className="rounded-2xl bg-black border border-white/10 px-4 py-4"
            />

            <input
              placeholder="Compliance Status"
              value={complianceStatus}
              onChange={(e) => setComplianceStatus(e.target.value)}
              className="rounded-2xl bg-black border border-white/10 px-4 py-4"
            />

            <input
              placeholder="Risk Score"
              value={riskScore}
              onChange={(e) => setRiskScore(e.target.value)}
              className="rounded-2xl bg-black border border-white/10 px-4 py-4"
            />

            <input
              placeholder="Industry"
              value={industry}
              onChange={(e) => setIndustry(e.target.value)}
              className="rounded-2xl bg-black border border-white/10 px-4 py-4"
            />

            <input
              placeholder="Framework (NIST, ISO 27001, SOC2)"
              value={framework}
              onChange={(e) => setFramework(e.target.value)}
              className="rounded-2xl bg-black border border-white/10 px-4 py-4"
            />

            <input
              type="file"
              onChange={(e) =>
                setSelectedFile(e.target.files?.[0] || null)
              }
              className="rounded-2xl bg-black border border-white/10 px-4 py-4"
            />

          </div>

          <textarea
            placeholder="Security Findings"
            value={findings}
            onChange={(e) => setFindings(e.target.value)}
            className="mt-6 w-full rounded-2xl bg-black border border-white/10 px-4 py-4 min-h-[120px]"
          />

          <textarea
            placeholder="Recommendations"
            value={recommendations}
            onChange={(e) => setRecommendations(e.target.value)}
            className="mt-6 w-full rounded-2xl bg-black border border-white/10 px-4 py-4 min-h-[120px]"
          />

          <button
            onClick={addClient}
            className="mt-6 rounded-2xl bg-white text-black px-6 py-4 font-semibold hover:bg-zinc-200 transition"
          >
            Create Assessment
          </button>
        </div>

        {loading ? (
          <p>Loading assessments...</p>
        ) : (
          <div className="grid gap-6">
            {clients.map((client) => (
              <div
                key={client.id}
                className="rounded-3xl border border-white/10 bg-white/5 p-8"
              >
                <div className="flex flex-col gap-6">

                  <div className="flex flex-col md:flex-row md:justify-between gap-4">

                    <div>
                      <h2 className="text-3xl font-bold">
                        {client.company_name}
                      </h2>

                      <p className="text-zinc-400 mt-2">
                        {client.contact_name}
                      </p>

                      <p className="text-zinc-500">
                        {client.email}
                      </p>
                    </div>

                    <div className="text-right">
                      <p className="text-zinc-500 text-sm">
                        Compliance
                      </p>

                      <p className="text-xl font-semibold">
                        {client.compliance_status}
                      </p>

                      <p className="mt-4 text-zinc-500 text-sm">
                        Risk Score
                      </p>

                      <p className="text-3xl font-bold text-blue-400">
                        {client.risk_score}
                      </p>
                    </div>
                  </div>

                  <div className="grid md:grid-cols-2 gap-6">

                    <div className="rounded-2xl bg-black/40 p-6">
                      <h3 className="text-lg font-semibold mb-3">
                        Assessment Details
                      </h3>

                      <p>
                        <span className="text-zinc-500">
                          Industry:
                        </span>{" "}
                        {client.industry}
                      </p>

                      <p className="mt-2">
                        <span className="text-zinc-500">
                          Framework:
                        </span>{" "}
                        {client.framework}
                      </p>
                    </div>

                    <div className="rounded-2xl bg-black/40 p-6">
                      <h3 className="text-lg font-semibold mb-3">
                        Findings
                      </h3>

                      <p className="text-zinc-400">
                        {client.findings}
                      </p>
                    </div>

                  </div>

                  <div className="rounded-2xl bg-black/40 p-6">
                    <h3 className="text-lg font-semibold mb-3">
                      Recommendations
                    </h3>

                    <p className="text-zinc-400">
                      {client.recommendations}
                    </p>
                  </div>

                  <div className="flex gap-4">

                    {client.document_url && (
                      <a
                        href={client.document_url}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="rounded-xl bg-zinc-800 px-5 py-3 hover:bg-zinc-700 transition"
                      >
                        View Evidence
                      </a>
                    )}

                    <button
                      onClick={() => generatePDF(client)}
                      className="rounded-xl bg-blue-500 px-5 py-3 hover:bg-blue-400 transition"
                    >
                      Download Report
                    </button>

                  </div>

                </div>
              </div>
            ))}
          </div>
        )}
      </div>
    </main>
  );
}